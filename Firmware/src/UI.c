//==============================================================================
// Private Function Prototypes
//==============================================================================
static void ui_handler(void* args);

//==============================================================================
// Variables
//==============================================================================
K_THREAD_DEFINE(_uiThread, 1024, ui_handler, NULL, NULL, NULL, 4, 0, -1);

//==============================================================================
// Public Functions
//==============================================================================
int Ui_Init() {
	LOG_INF("Initializing");
	return 0;
}

int Ui_Start() {
	LOG_INF("Starting");
	k_thread_start(_uiThread);
	return 0;
}

//==============================================================================
// Private Functions
//==============================================================================


//==============================================================================
// Task Handler
//==============================================================================
static void ui_handler(void* args) {

	while(1) {
		k_msleep(1000);
	}
}

